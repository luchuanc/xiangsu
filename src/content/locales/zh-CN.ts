const rawIdPattern = /(?:^|[^A-Za-z0-9_])(?:char|skill|effect|status|eq|equip|af|affix|tr|sa|skill_affix|combo|enemy|boss|encounter|modifier|intent|echo|floor|map|npc|dialogue|quest|recruit|recruitment|shop|item|drop|tag|skill_family)[._][A-Za-z0-9_]+(?:$|[^A-Za-z0-9_])/;

function localeKeyFingerprint(keys: readonly string[]): string {
  let hash = 0x811c9dc5;
  for (const byte of new TextEncoder().encode([...keys].sort().join("\n"))) {
    hash ^= byte;
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

