/** 校验精确 key 集、token 集与 raw ID 泄漏，失败统一返回 INVALID_CONTENT。 */
export function validateLocale(locale: Record<string, string>): { ok: true; value: true } | { ok: false; error: { code: "INVALID_CONTENT"; details: { path: string; issueKey: string } } } {
  const actual = Object.keys(locale);
  if (actual.length !== FROZEN_LOCALE_KEY_COUNT || localeKeyFingerprint(actual) !== FROZEN_LOCALE_KEY_FNV1A32) return { ok: false, error: { code: "INVALID_CONTENT", details: { path: "locale", issueKey: "locale.key_set" } } };

  const categoryCounts = {
    contentNames: actual.filter((key) => key.endsWith(".name")).length,
    contentDescriptions: actual.filter((key) => key.endsWith(".description")).length,
    dialogues: actual.filter((key) => key.startsWith("dialogue.")).length,
    locks: actual.filter((key) => key.startsWith("lock.")).length,
    comboTags: actual.filter((key) => key.startsWith("tag.")).length,
    skillFamilies: actual.filter((key) => key.startsWith("skill_family.")).length,
    skillAffixTargets: actual.filter((key) => key.startsWith("skill_affix_target.")).length,
    modifiers: actual.filter((key) => key.startsWith("modifier.")).length,
    skillAffixOperations: actual.filter((key) => key.startsWith("skill_affix_operation.")).length,
    errorTemplates: actual.filter((key) => key.startsWith("error.")).length,
  };
  for (const [category, expectedCount] of Object.entries(localeCounts)) {
    if (categoryCounts[category as keyof typeof categoryCounts] !== expectedCount) return { ok: false, error: { code: "INVALID_CONTENT", details: { path: `locale.${category}`, issueKey: "locale.category_count" } } };
  }
  const actualErrors = actual.filter((key) => key.startsWith("error.")).sort();
  if (actualErrors.join("\0") !== [...frozenErrorTemplateKeys].sort().join("\0")) return { ok: false, error: { code: "INVALID_CONTENT", details: { path: "locale.error", issueKey: "locale.error_key_set" } } };
  for (const [key, value] of Object.entries(locale)) {
    if (typeof value !== "string" || value.length === 0 || value === key || rawIdPattern.test(value)) return { ok: false, error: { code: "INVALID_CONTENT", details: { path: key, issueKey: "locale.raw_or_empty" } } };
    const actualTokens = [...value.matchAll(tokenPattern)].map((match) => match[1]).sort();
    const expectedTokens = [...(localeTokenSpec[key] ?? [])].sort();
    if (actualTokens.join("\0") !== expectedTokens.join("\0")) return { ok: false, error: { code: "INVALID_CONTENT", details: { path: key, issueKey: "locale.token_set" } } };
  }
  return { ok: true, value: true };
}
